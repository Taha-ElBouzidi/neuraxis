function emit(path, content, volatile) {
    if (CHECK && volatile)
        return;
    if (!CHECK) {
        writeFileSync(path, content, 'utf8');
        return;
    }
    let current = '';
    try {
        current = readFileSync(path, 'utf8');
    }
    catch {
        drift.push(`${path} (missing)`);
        return;
    }
    if (current.replace(/\r\n/g, '\n') !== content.replace(/\r\n/g, '\n'))
        drift.push(path);
}
